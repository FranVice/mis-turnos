from playwright.sync_api import sync_playwright, expect
import sys, re
sys.stdout.reconfigure(encoding='utf-8')
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':393,'height':852},is_mobile=True,has_touch=True,timezone_id='Europe/Madrid')
    errors=[]
    page.on('pageerror',lambda e: errors.append(str(e)))
    page.on('dialog',lambda dialog: dialog.accept())
    page.goto('http://localhost:8083')
    expect(page.get_by_text('Franklin (tú)',exact=True)).to_be_visible(timeout=60000)
    for width in (320,375,393,430,768):
        page.set_viewport_size({'width':width,'height':852})
        assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), f'desbordamiento {width}'
    page.set_viewport_size({'width':393,'height':852})
    page.get_by_label('Mes siguiente',exact=True).click()
    page.get_by_role('button',name='Día 1, sin turnos',exact=True).click()
    page.get_by_role('button',name='Añadir turno',exact=True).click()
    expect(page.get_by_role('radio',name='Noche',exact=True)).to_be_visible()
    page.get_by_role('radio',name='Noche',exact=True).click()
    expect(page.get_by_label('Entrada',exact=True)).to_have_value('22:00')
    expect(page.get_by_label('Salida',exact=True)).to_have_value('06:00')
    page.get_by_role('button',name='Guardar turno',exact=True).click()
    expect(page.get_by_text('acaba al día siguiente',exact=True)).to_be_visible()
    page.get_by_text('Cerrar',exact=True).click()
    page.get_by_role('button',name='Varios días',exact=True).click()
    for day in range(2,7): page.get_by_role('button',name=f'Día {day}, sin turnos',exact=True).click()
    page.get_by_role('button',name='Asignar turno',exact=True).click()
    page.get_by_role('radio',name='Almudena',exact=True).click()
    expect(page.get_by_label('Entrada',exact=True)).to_have_value('')
    page.get_by_label('Entrada',exact=True).fill('09:15')
    page.get_by_label('Salida',exact=True).fill('16:45')
    expect(page.get_by_text('Se van a guardar 5 de 5 días',exact=True)).to_be_visible()
    page.get_by_role('button',name='Guardar 5 días',exact=True).click()
    expect(page.get_by_role('button',name='Varios días',exact=True)).to_be_visible()
    page.get_by_role('button',name=re.compile(r'^Día 2,')).click()
    page.get_by_text('09:15–16:45',exact=True).click()
    page.get_by_role('radio',name='Vacaciones',exact=True).click()
    expect(page.get_by_text('Día completo, sin horas obligatorias.',exact=True)).to_be_visible()
    page.get_by_role('button',name='Guardar cambios',exact=True).click()
    expect(page.get_by_text('Día completo',exact=True)).to_be_visible()
    page.get_by_text('Día completo',exact=True).click()
    page.get_by_role('button',name='Eliminar turno',exact=True).click()
    expect(page.get_by_text('Sin turnos este día.',exact=True)).to_be_visible()
    page.get_by_text('Cerrar',exact=True).click()
    page.get_by_label('Horarios habituales y cuenta',exact=True).click()
    expect(page.get_by_text('Color de Franklin',exact=True)).to_be_visible()
    page.get_by_role('radio',name='Color #15803D para Franklin',exact=True).click()
    expect(page.get_by_role('radio',name='Color #15803D para Franklin',exact=True)).to_have_attribute('aria-checked','true')
    page.get_by_text('Cerrar',exact=True).click()
    page.screenshot(path='.expo/calendar-checked.png',full_page=True)
    assert errors==[],errors
    print('OK: 320–768 px, noche, cinco días, horas propias de Almudena, vacaciones, edición, eliminación, colores; sin errores JS.')
    browser.close()
